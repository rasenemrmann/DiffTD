export function pickLanguage(languages = globalThis.navigator?.languages ?? []) {
  for (const l of languages) {
    const base = String(l).toLowerCase().split('-')[0];
    if (base in STRINGS) return base;
  }
  return 'en';
}

let current = pickLanguage();

export function setLanguage(lang) {
  current = lang in STRINGS ? lang : 'en';
}

export function getLanguage() {
  return current;
}

/** t('key', { n: 3 }). Unknown keys fall back to English, then to the key itself. */
export function t(key, params = {}, lang = current) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in params ? String(params[name]) : `{${name}}`));
}
